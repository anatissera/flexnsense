"""NormaCore Station client: the only way we talk to the ElRobot.

There is no LeRobot support for the ElRobot (confirmed upstream: no robot type, no driver).
Everything goes through NormaCore's own binary, Station, over a plain TCP protocol. The
parsing in `parse_motor_state` and the connect/subscribe/command flow below are ported from
NormaCore's own examples (`software/station/shared/station_py/example_follow.py` and
`example_commands.py` in https://github.com/norma-core/norma-core), not guessed.

Setup (see SETUP.md): sparse-clone norma-core, generate the protobufs, and put the repo on
PYTHONPATH via a .pth file. That is what makes `target.gen_python.protobuf.*` importable
below; it is a lazy import so this module still loads (and its pure parsing is testable)
without that setup done.

    import asyncio
    from lib.station import connect, follow_motor_state

    async def main():
        client = await connect("localhost")
        async for bus_serial, motor_id, state in follow_motor_state(client):
            print(bus_serial, motor_id, state)

    asyncio.run(main())

Station's own safety net lives in station.yaml (current-threshold, per-motor
motor-current-thresholds), not in this module - see docs/elrobot.md.
"""
from __future__ import annotations

import logging
import struct
from dataclasses import dataclass

DEFAULT_STATION_PORT = 8888
QUEUE_MOTOR_STATE = "st3215/inference"

# ST3215 register offsets within the raw state blob Station streams (protocol/memory.rs
# upstream; also the offsets `example_follow.py` uses). Present_Load is not read here: we
# don't need it, current is our force proxy and it's what NormaCore's own example reads.
_POSITION_ADDR = 0x38      # 2 bytes
_VOLTAGE_ADDR = 0x3E       # 1 byte, 0.1 V units
_TEMPERATURE_ADDR = 0x3F   # 1 byte, degrees C
_CURRENT_ADDR = 0x45       # 2 bytes, milliamps directly (Station already decodes this)

# RAM registers for writing, confirmed from NormaCore's own examples (state.py / st3215.py in
# st3215-remote-teleop-py and so101-autocalibration-py), not guessed.
RAM_TORQUE_ENABLE = 0x28   # 1 byte, 0 or 1
RAM_GOAL_POSITION = 0x2A   # 2 bytes

_MAX_ANGLE_STEP = 4095
_SIGN_BIT_MASK = 0x8000


@dataclass(frozen=True)
class MotorState:
    position: int | None       # raw ticks, sign-corrected; None if the blob was too short
    current_ma: int | None
    temperature_c: int | None
    voltage_v: float | None
    range_min: int
    range_max: int


def _normalize_position(raw: int) -> int:
    """STS3215 encodes direction in the sign bit of the 16-bit position word."""
    if raw & _SIGN_BIT_MASK:
        magnitude = raw & _MAX_ANGLE_STEP
        return (_MAX_ANGLE_STEP + 1 - magnitude) & _MAX_ANGLE_STEP
    return raw & _MAX_ANGLE_STEP


def parse_motor_state(state_bytes: bytes, range_min: int = 0, range_max: int = 0) -> MotorState:
    """Decode one motor's raw state blob, as streamed on the `st3215/inference` queue.

    Fields are read only if the blob is long enough to contain them (older firmware or a
    truncated read may not carry all of them); missing fields come back as None rather than
    a wrong zero, so a caller can tell "not reported" from "reported as zero".
    """
    position = current = temperature = None
    voltage = None

    if len(state_bytes) >= _POSITION_ADDR + 2:
        raw = struct.unpack("<H", state_bytes[_POSITION_ADDR:_POSITION_ADDR + 2])[0]
        position = _normalize_position(raw)

    if len(state_bytes) >= _CURRENT_ADDR + 2:
        current = struct.unpack("<H", state_bytes[_CURRENT_ADDR:_CURRENT_ADDR + 2])[0]

    if len(state_bytes) >= _TEMPERATURE_ADDR + 1:
        temperature = state_bytes[_TEMPERATURE_ADDR]

    if len(state_bytes) >= _VOLTAGE_ADDR + 1:
        voltage = state_bytes[_VOLTAGE_ADDR] / 10.0

    return MotorState(position, current, temperature, voltage, range_min, range_max)


def _import_generated():
    """The protobuf modules generated by the norma-core setup step (see SETUP.md). Lazy, so
    this module imports cleanly (and its pure parsing is testable) before that setup runs."""
    try:
        from station_py import StreamEntry, new_station_client, send_commands
        from target.gen_python.protobuf.drivers.st3215 import st3215
        from target.gen_python.protobuf.station import commands, drivers
    except ImportError as exc:
        raise SystemExit(
            f"error: norma-core Python client not set up ({exc}).\n"
            "  Run the sparse-clone + protobuf-generation steps in SETUP.md, with this\n"
            "  environment active, then retry."
        ) from exc
    return StreamEntry, new_station_client, send_commands, st3215, commands, drivers


async def connect(host: str = "localhost", port: int = DEFAULT_STATION_PORT, logger=None):
    """Connect to a running Station (`./station --web ... --tcp ...`), default port 8888."""
    _, new_station_client, *_ = _import_generated()
    logger = logger or logging.getLogger("lib.station")
    addr = host if ":" in host else f"{host}:{port}"
    return await new_station_client(addr, logger)


async def follow_motor_state(client):
    """Yield (bus_serial, motor_id, MotorState) forever, as Station streams them.

    One entry on the wire carries every bus and every motor on it; this flattens that into
    one tuple per motor, so a caller filters by bus_serial/motor_id instead of parsing
    nested protobuf structures itself.
    """
    import asyncio

    StreamEntry, _, _, st3215, _, _ = _import_generated()

    entries: "asyncio.Queue" = asyncio.Queue()
    errors = client.follow(QUEUE_MOTOR_STATE, entries)

    while True:
        if not errors.empty():
            raise RuntimeError(f"Station subscription error: {await errors.get()}")

        try:
            entry: StreamEntry = await asyncio.wait_for(entries.get(), timeout=1.0)
        except asyncio.TimeoutError:
            continue
        if entry is None:
            return

        inference = st3215.InferenceStateReader(memoryview(bytes(entry.Data)))
        for bus in inference.get_buses() or []:
            bus_info = bus.get_bus()
            if not bus_info:
                continue
            bus_serial = bus_info.get_serial_number()
            for motor in bus.get_motors() or []:
                state_bytes = motor.get_state()
                if not state_bytes:
                    continue
                state = parse_motor_state(
                    bytes(state_bytes), motor.get_range_min(), motor.get_range_max()
                )
                yield bus_serial, motor.get_id(), state


async def set_position(client, bus_serial: str, motor_id: int, position: int) -> None:
    """Write a raw target position (ticks) to one motor. Does not clamp to range_min/max:
    the caller already has that from follow_motor_state and owns the safety decision."""
    _, _, send_commands, st3215, commands, drivers = _import_generated()

    write_cmd = st3215.Command(
        target_bus_serial=bus_serial,
        write=st3215.ST3215WriteCommand(
            motor_id=motor_id,
            address=RAM_GOAL_POSITION,
            value=position.to_bytes(2, byteorder="little"),
        ),
    )
    cmd = commands.DriverCommand(
        type=drivers.StationCommandType.STC_ST3215_COMMAND, body=write_cmd.encode()
    )
    await send_commands(client, [cmd])


async def sync_write(client, bus_serial: str, address: int, values: dict[int, bytes]) -> None:
    """Write the same register on several motors in one packet. {motor_id: raw_value_bytes}."""
    _, _, send_commands, st3215, commands, drivers = _import_generated()

    cmd = st3215.Command(
        target_bus_serial=bus_serial,
        sync_write=st3215.ST3215SyncWriteCommand(
            address=address,
            motors=[
                st3215.ST3215SyncWriteCommand_MotorWrite(motor_id=mid, value=val)
                for mid, val in values.items()
            ],
        ),
    )
    driver_cmd = commands.DriverCommand(
        type=drivers.StationCommandType.STC_ST3215_COMMAND, body=cmd.encode()
    )
    await send_commands(client, [driver_cmd])


async def set_torque(client, bus_serial: str, motor_ids: list[int], enable: bool) -> None:
    """Enable or disable torque on several motors at once. With torque off a joint is limp
    (backdrivable); with it on and a goal position set, the servo actively holds that position
    and resists being moved away from it, which is what makes the arm a rigid anchor."""
    value = b"\x01" if enable else b"\x00"
    await sync_write(client, bus_serial, RAM_TORQUE_ENABLE, {mid: value for mid in motor_ids})


def build_freeze_arcs(ranges: dict[int, tuple[int, int]]) -> list[tuple[int, int, int, int]]:
    """{motor_id: (range_min, range_max)} -> [(motor_id, min_angle, max_angle, midpoint), ...].

    Pure and protobuf-free, so it is unit-tested directly (see tests/lib/test_station.py).
    `midpoint` is not something we ever read back from a motor (InferenceState.MotorState has
    no such field) - it is derived here as the arithmetic mean, a reasonable default, not a
    recovered original value.
    """
    return [(motor_id, lo, hi, (lo + hi) // 2) for motor_id, (lo, hi) in ranges.items()]


async def freeze_calibration(client, bus_serial: str, ranges: dict[int, tuple[int, int]]) -> None:
    """Write a joint-range calibration straight to the servos' firmware, skipping the manual
    move-every-joint-through-its-range flow in Station's web UI.

    For restoring a calibration recorded in config/calibration/ after it was lost (servo reset,
    replacement, reflash) - not for performing a first calibration, which still has to be done
    by hand once, by actually moving the joint, so `ranges` reflects where the joint can really go.
    """
    _, _, send_commands, st3215, commands, drivers = _import_generated()

    arcs = [
        st3215.FreezeMotorArc(motor_id=mid, min_angle=lo, max_angle=hi, midpoint=mid_)
        for mid, lo, hi, mid_ in build_freeze_arcs(ranges)
    ]
    freeze_cmd = st3215.Command(
        target_bus_serial=bus_serial,
        freeze_calibration=st3215.FreezeCalibrationCommand(freeze=True, arcs=arcs),
    )
    cmd = commands.DriverCommand(
        type=drivers.StationCommandType.STC_ST3215_COMMAND, body=freeze_cmd.encode()
    )
    await send_commands(client, [cmd])
